    // ======================= НАВЫКИ: ранг с прогрессом (общий механизм, пока без боя и сохранения) =======================
    // Ранг умения считается из накопленных очков; хранить будем только очки, чтобы ранг и очки не могли разойтись.
    const SKILL_WALL = 7; // до этого ранга умение растёт само, дальше нужен учитель (стена одна для всех, решение автора)

    // Очки за одно применение умения в бою: обычное и «хороший ответ» на приём врага (решение автора: чтение намерений ценнее спама).
    const SKILL_POINTS = { use: 1, good: 2 };

    // Сколько очков нужно накопить, чтобы получить этот ранг: первый бесплатный, дальше растёт квадратично (числа черновые).
    const skillCost = rank => 10 * (rank - 1) ** 2;

    // Ранг и прогресс к следующему в процентах. cap — потолок ранга: пока стена, позже учитель передаст сюда больше.
    function skillRank(points, cap = SKILL_WALL) {
      let rank = 1;
      while (rank < cap && points >= skillCost(rank + 1)) rank += 1;
      if (rank === cap) return { rank, percent: 100 };
      const from = skillCost(rank);
      const percent = Math.floor((points - from) / (skillCost(rank + 1) - from) * 100);
      return { rank, percent };
    }

    // Сила ранга: каждый ранг выше первого усиливает умение на эту долю (числа черновые, настраиваются симуляцией).
    // Атака бьёт сильнее, защита сильнее гасит урон, воздействие чаще срабатывает.
    const SKILL_RANK_STEP = 0.05;
    const rankPower = rank => SKILL_RANK_STEP * (rank - 1);

    // Умения, у которых есть ранги. Новое умение с рангами нужно добавить сюда вручную.
    const RANKED_SKILLS = ["frostBolt", "barrier", "timidity"];

    // Очки умений из сохранения: только известные умения, целые неотрицательные числа. Старые сохранения без поля дают нули (ранг 1).
    // Назван skillPoints, потому что p.skills и cleanSkills уже заняты старой боевой системой.
    function cleanSkillPoints(raw) {
      const out = {};
      for (const key of RANKED_SKILLS) {
        const n = raw?.[key];
        out[key] = Number.isFinite(n) && n > 0 ? Math.floor(n) : 0;
      }
      return out;
    }
